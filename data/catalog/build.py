class _Flow(dict[str, Any]):
    """A mapping written on one line, `{a: 1, b: 2}`."""


class _FlowList(list[Any]):
    """A list written on one line, `[a, b]`."""


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data: Any) -> bool:
        return True


_Dumper.add_representer(
    _Flow, lambda d, data: d.represent_mapping("tag:yaml.org,2002:map", data, flow_style=True)
)
_Dumper.add_representer(
    _FlowList, lambda d, data: d.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=True)
)


def _data_type(sql_type: str) -> str:
    if sql_type.startswith("decimal"):
        return "decimal"
    return _TYPE_NAMES[sql_type]


def _column(table: TableSpec, column: ColumnSpec) -> _Flow:
    entry = _Flow(
        name=column.name,
        data_type=_data_type(column.sql_type),
        native_type=column.sql_type,
        nullable=column.name not in table.primary_key,
        is_primary_key=column.name in table.primary_key,
        description=column.catalog_description,
    )
    if column.is_personal:
        entry["tags"] = _FlowList([PERSONAL_TAG])
    return entry


def _dataset(table: TableSpec) -> dict[str, Any]:
    fqn = f"{ENGINE_PREFIX}.{table.name}"
    return {
        "engine_fqn": fqn,
        "catalog_id": fqn,
        "name": table.name,
        "description": table.catalog_description,
        "owners": _FlowList([_Flow(OWNER)]),
        "columns": [_column(table, c) for c in table.columns],
    }


def build_export() -> dict[str, Any]:
    """The export as plain data, in file order."""
    return {
        "format": FORMAT,
        "source": _Flow(name=SOURCE_NAME, exported_at=EXPORTED_AT),
        "datasets": [_dataset(t) for t in TABLES],
        "glossary_terms": [
            _Flow(
                catalog_id=t["catalog_id"],
                name=t["name"],
                definition=t["definition"],
                synonyms=_FlowList(t["synonyms"]),
            )
            for t in GLOSSARY_TERMS
        ],
    }


def render_export() -> str:
    """The exact text of the committed file."""
    body = yaml.dump(
        build_export(),
        Dumper=_Dumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=10_000,
    )
    return HEADER + body
